def art(text):
	rows = [r for r in text.strip('\n').split('\n')]
	w = max(len(r) for r in rows)
	return w, len(rows), [LEV[c] for r in rows for c in r.ljust(w, '.')]

def drawn(n, f):
	g, a = shape(n, f)
	px = [(g.getpixel((x, y)) // 17) if a.getpixel((x, y)) else T for y in range(n) for x in range(n)]
	return n, n, px

