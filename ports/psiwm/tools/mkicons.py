K, D, L, W = 0, 85, 170, 255

def quant(im, levels=(0, 85, 170, 255)):
	return im.point(lambda v: min(levels, key=lambda g: abs(g - v)))

def shape(n, draw, bg=None):
	"""draw(d, R) at 4x on transparent; returns (grey L image, mask)"""
	S = 4; N = n * S
	R = lambda v: int(round(v * N / n))
	g = Image.new('L', (N, N), W)
	a = Image.new('L', (N, N), 0)
	dg = ImageDraw.Draw(g); da = ImageDraw.Draw(a)
	class Both:
		def __getattr__(s, name):
			def f(xy, *args, fill=None, outline=None, width=1, **kw):
				# shapes are given in icon pixels; the 4x is applied here
				def sc(v):
					if isinstance(v, (list, tuple)):
						return [sc(u) for u in v]
					return R(v)
				xy = sc(xy)
				w = max(1, R(width))
				kwg = dict(kw); kwa = dict(kw)
				if 'radius' in kw:
					kwg['radius'] = kwa['radius'] = R(kw['radius'])
				if name in ('line',):
					getattr(dg, name)(xy, fill=fill, width=w, **kwg)
					getattr(da, name)(xy, fill=255, width=w, **kwa)
				elif name == 'arc' or name == 'pieslice' and False:
					getattr(dg, name)(xy, *args, fill=fill, width=w, **kwg)
					getattr(da, name)(xy, *args, fill=255, width=w, **kwa)
				else:
					getattr(dg, name)(xy, *args, fill=fill, outline=outline, width=w, **kwg)
					getattr(da, name)(xy, *args, fill=255 if fill is not None else None,
						outline=255 if outline is not None else None, width=w, **kwa)
			return f
	draw(Both())
	g = quant(g.resize((n, n), Image.BOX))
	a = a.resize((n, n), Image.BOX).point(lambda v: 255 if v >= 110 else 0)
	return g, a

