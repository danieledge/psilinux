#!/usr/bin/env python3
# Makes font.h: psiwm's bitmap fonts, rendered once (no anti-aliasing, hinted)
# from Liberation Sans and Nimbus Sans Narrow, whose metrics follow Arial and
# Helvetica, as the Psion's own system fonts do. (Both are free fonts: SIL OFL
# 1.1 and AGPL-with-font-exception; the bitmaps carry their notices in
# THIRD-PARTY.) Run on the build host: python3 mkfont.py > ../font.h
# Each font: ASCII 32-126, then 127 = U+2026 ellipsis, 128 = (c), 129 = degree,
# 130 = pound, 131 times, 132 divide, 133 minus, 134 plus-minus. A glyph: advance, x offset, width; rows of (w+7)/8 bytes, LSB
# first (bit 0 = leftmost pixel), full font height.
import sys
from PIL import Image, ImageDraw, ImageFont
L = '/usr/share/fonts/truetype/liberation/'
N = '/usr/share/fonts/opentype/urw-base35/'
FONTS = [   # (C name, file, pixel size, characters)
	('f_small',  L + 'LiberationSans-Regular.ttf', 11, None),
	('f_normal', L + 'LiberationSans-Regular.ttf', 13, None),
	('f_large',  L + 'LiberationSans-Regular.ttf', 16, None),
	('f_bold',   L + 'LiberationSans-Bold.ttf', 13, None),
	('f_title',  L + 'LiberationSans-Bold.ttf', 15, None),
	('f_dense',  N + 'NimbusSansNarrow-Bold.otf', 12, None),
	('f_huge',   L + 'LiberationSans-Bold.ttf', 44, 'PsiLnux'),
	('f_big',    L + 'LiberationSans-Bold.ttf', 30, '0123456789:.-+=/%*E ' + chr(0x2026) + chr(0x2212)),
]
EXTRA = [0x2026, 0xA9, 0xB0, 0xA3, 0xD7, 0xF7, 0x2212, 0xB1]
out = sys.stdout
out.write('/* font.h - generated by tools/mkfont.py: do not edit */\n')
out.write('typedef struct { unsigned char adv, xo, w; unsigned short off; } Glyph;\n')
out.write('typedef struct { unsigned char h, asc, first, n; const Glyph *g; const unsigned char *bits; } BFont;\n')
out.write('extern const BFont ' + ', '.join(f[0] for f in FONTS) + ';\n#ifdef FONT_DATA\n')
for name, path, size, chars in FONTS:
	F = ImageFont.truetype(path, size)
	asc, desc = F.getmetrics()
	h = asc + desc
	codes = list(range(32, 127)) + EXTRA
	glyphs, bits = [], []
	for i, c in enumerate(codes):
		ch = chr(c)
		if chars is not None and ch not in chars:
			glyphs.append((0, 0, 0, 0)); continue
		adv = int(round(F.getlength(ch)))
		im = Image.new('1', (adv + size, h), 0)
		d = ImageDraw.Draw(im); d.fontmode = '1'
		d.text((size // 2, 0), ch, font=F, fill=1)
		bb = im.getbbox()
		if not bb:
			glyphs.append((adv, 0, 0, len(bits))); continue
		x0, x1 = bb[0], bb[2]
		w = x1 - x0
		xo = x0 - size // 2
		if xo < 0: adv += 0; 
		off = len(bits)
		for y in range(h):
			for bx in range(0, w, 8):
				v = 0
				for k in range(8):
					if bx + k < w and im.getpixel((x0 + bx + k, y)): v |= 1 << k
				bits.append(v)
		glyphs.append((adv, max(xo, 0), w, off))
	out.write('static const Glyph %s_g[%d] = {' % (name, len(codes)))
	out.write(','.join('{%d,%d,%d,%d}' % g for g in glyphs))
	out.write('};\nstatic const unsigned char %s_b[%d] = {' % (name, max(len(bits), 1)))
	for i in range(0, len(bits), 32):
		out.write('\n' + ','.join(str(b) for b in bits[i:i+32]) + ',')
	out.write('};\n')
	out.write('const BFont %s = { %d, %d, 32, %d, %s_g, %s_b };\n' % (name, h, asc, len(codes), name, name))
out.write('#endif\n')
